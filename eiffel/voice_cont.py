import sys
from pathlib import Path

sys.path.insert(0, "/root/tts-bridge")
from narrator import Narrator

TEXT = [
    "Эйфелева башня становится выше на пятнадцать сантиметров каждый день.",
    "Металл нагревается на солнце и расширяется.",
    "Днём вершина поднимается, а ночью опускается обратно.",
    "Это видно по зазорам в конструкции.",
    "Летом разница особенно заметна: башня гуляет вверх и вниз, как живая.",
    "Её высота триста метров, а вместе с антенной триста тридцать метров.",
    "Весит она около десяти тысяч тонн.",
    "Построили её в тысяча восемьсот восемьдесят девятом году для выставки.",
    "А ещё железо ржавеет, поэтому башню красят каждые семь лет, слой за слоем.",
    "Каждые несколько лет её осматривают, счищают старую краску и наносят новую вручную.",
    "Так она и стоит — живая, железная, и каждый день чуть выше.",
]

n = Narrator(voice="eugene", lead=0.05, gap=0.12, delay_ms=600)
mix = n.track([(0.25, TEXT)], total=42.0, out=Path("renders/voice_cont.wav"))
final = n.mux("renders/eiffel_v2.mp4", mix, "renders/eiffel_v2_voice.mp4")
print("ok", final.stat().st_size)
